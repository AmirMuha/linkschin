// Traceability gate. Parses the four spec.md files, then greps e2e/specs/** for a test
// title carrying each id. Exits 1 on any gap, so the matrix cannot silently rot.
//
//   node e2e/check-coverage.mjs          report + regenerate TRACEABILITY.md
//   node e2e/check-coverage.mjs --check  report only, never write
//
// The spec files carry no SC-### ids, so latency and telemetry scenarios are out of scope
// for this gate by construction rather than by an exemption list that could be gamed.
// They are documented in TRACEABILITY.md under "Not e2e-testable".
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, relative } from 'node:path'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO = join(HERE, '..')

const SPECS = [
  { id: '001', dir: '001-mvp' },
  { id: '002', dir: '002-ui-ux-redesign' },
  { id: '003', dir: '003-ai-assistant' },
  { id: '004', dir: '004-source-suggestions' },
  { id: '007', dir: '007-source-filters-movie-details' },
]

/** Wall-clock and population requirements. Recorded, not skipped silently. */
const NOT_E2E = {
  '001-SC-001': 'latency <2s — flaky against a dev server',
  '001-SC-002': 'latency <12s — flaky against a dev server',
  '001-SC-003': 'needs usage telemetry, not a fixture',
  '001-SC-004': 'needs usage telemetry, not a fixture',
  '002-SC-001': 'latency budget (<1.5s/500ms/10s) — flaky against a dev server',
  '003-SC-001': 'latency <2s first token — flaky against a dev server',
  '003-SC-002': 'latency <12s total — flaky against a dev server',
  '003-SC-004': 'latency — flaky against a dev server',
  '003-SC-005': 'needs conversation population data',
  '003-SC-006': 'latency — flaky against a dev server',
  '003-SC-008': 'needs conversation population data',
  '004-SC-001': 'monthly suggestion volume — not observable from a test',
  '004-SC-004': 'latency <50ms — flaky against a dev server',
  '007-SC-001': 'latency <50ms — flaky against a dev server',
}

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name)
    return statSync(p).isDirectory() ? walk(p) : [p]
  })
}

const specFiles = walk(join(HERE, 'specs')).filter((p) => p.endsWith('.spec.ts'))
if (!specFiles.length) {
  console.error('check-coverage: no spec files under e2e/specs/ — nothing to check.')
  process.exit(1)
}
const titles = specFiles
  // Indented inside test.describe, hence the leading \s* — without it nothing matches.
  .map((p) => ({ file: relative(REPO, p), tests: readFileSync(p, 'utf8').matchAll(/^\s*test(?:\.\w+)?\(\s*(['"`])(.*?)\1/gm) }))
  .flatMap(({ file, tests }) => [...tests].map((m) => ({ file, title: m[2] })))

const covered = { fr: new Set(), ac: new Set(), us: new Set() }
for (const { title } of titles) {
  for (const m of title.matchAll(/\[(0\d\d)-US(\d+)(?:-AC(\d+))?\]/g)) {
    covered.us.add(`${m[1]}-US${m[2]}`)
    if (m[3]) covered.ac.add(`${m[1]}-US${m[2]}-AC${m[3]}`)
  }
  // Title carries [FR-001]; the spec it belongs to is the first [0NN-...] tag.
  const spec = title.match(/\[(0\d\d)-US\d+/)?.[1]
  for (const m of title.matchAll(/\[FR-(\d{3})\]/g)) if (spec) covered.fr.add(`${spec}-FR-${m[1]}`)
}

const missing = { fr: [], ac: [], us: [] }
const rows = []
let totalAC = 0
let totalFR = 0
let totalUS = 0

for (const { id, dir } of SPECS) {
  const md = readFileSync(join(REPO, 'specs', dir, 'spec.md'), 'utf8')

  const frs = [...md.matchAll(/^- \*\*(FR-\d{3})\*\*/gm)].map((m) => m[1])
  const usHeads = [...md.matchAll(/^### User Story (\d+) - (.*)$/gm)]
  // Acceptance scenarios are the numbered **Given** items under each user story; the specs
  // carry no AC-### ids, so the suite synthesises <spec>-US<n>-AC<m> from position.
  const acs = usHeads.map((u) => {
    const start = md.indexOf(u[0])
    const next = md.indexOf('### User Story', start + 1)
    const body = md.slice(start, next === -1 ? md.length : next)
    return { n: Number(u[1]), count: [...body.matchAll(/^\d+\.\s+\*\*Given\*\*/gm)].length }
  })

  totalFR += frs.length
  totalUS += usHeads.length
  totalAC += acs.reduce((n, a) => n + a.count, 0)

  for (const fr of frs) if (!covered.fr.has(`${id}-${fr}`)) missing.fr.push(`${id}-${fr}`)
  for (const u of acs) {
    if (!covered.us.has(`${id}-US${u.n}`)) missing.us.push(`${id}-US${u.n}`)
    for (let m = 1; m <= u.count; m++) {
      if (!covered.ac.has(`${id}-US${u.n}-AC${m}`)) missing.ac.push(`${id}-US${u.n}-AC${m}`)
    }
  }
  rows.push({ id, frs: frs.length, us: usHeads.length, ac: acs.reduce((n, a) => n + a.count, 0) })
}

const report = [
  '# E2E Traceability',
  '',
  'Generated by `node e2e/check-coverage.mjs`. Do not edit by hand — the gate regenerates it',
  'and exits non-zero on any gap.',
  '',
  '| Spec | Functional Reqs | User Stories | Acceptance Scenarios |',
  '|---|---|---|---|',
  ...rows.map((r) => `| ${r.id} | ${r.frs} | ${r.us} | ${r.ac} |`),
  `| **Total** | **${totalFR}** | **${totalUS}** | **${totalAC}** |`,
  '',
  `Tests carrying spec ids: **${titles.length}**`,
  '',
  '## Not e2e-testable',
  '',
  'Requirements that need wall-clock measurement or population data. The mechanism each one',
  'depends on is asserted elsewhere (cache badge, skeleton render, stale-response abort).',
  '',
  '| Id | Reason |',
  '|---|---|',
  ...Object.entries(NOT_E2E).map(([k, v]) => `| ${k} | ${v} |`),
  '',
]

const gaps = [
  ...missing.fr.map((x) => `  missing FR      ${x}`),
  ...missing.us.map((x) => `  missing US      ${x}`),
  ...missing.ac.map((x) => `  missing AC      ${x}`),
]

if (!process.argv.includes('--check')) {
  writeFileSync(join(HERE, 'TRACEABILITY.md'), report.join('\n'))
  console.log('wrote e2e/TRACEABILITY.md')
}

console.log(`FRs ${totalFR - missing.fr.length}/${totalFR}  US ${totalUS - missing.us.length}/${totalUS}  AC ${totalAC - missing.ac.length}/${totalAC}`)
if (gaps.length) {
  console.error(`\n${gaps.length} unmapped:\n${gaps.join('\n')}`)
  process.exit(1)
}
console.log('all mapped')
